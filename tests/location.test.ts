const response={country:'United States','post code':'80487',places:[{'place name':'Steamboat Springs','state abbreviation':'CO',latitude:'40.6327',longitude:'-106.9318'}]};
const request:typeof fetch=async()=>Response.json(response);
const filters=await resolveZip(filterSchema.parse({make:'Audi',model:'R8',zip:'80487',radiusMiles:50,state:'TX'}),request);
assert.equal(filters.location?.city,'Steamboat Springs');assert.equal(filters.state,'');
assert.equal(locationLabel(filters),'50 miles from Steamboat Springs, CO 80487');
assert.equal(zipInText('under 60000 miles'),undefined);assert.equal(zipInText('under $80487'),undefined);
assert.equal(basic('find R8 near 02108',initialFilters).filters.zip,'02108');
assert.equal(basic('find R8 near 80487 within 50 miles',initialFilters).filters.radiusMiles,50);
assert.equal(basic('nationwide',filters).filters.zip,'');assert.equal(basic('in California',filters).filters.zip,'');
assert.equal(localLocationCommand('80487',filters)?.filters.model,'R8');
assert.equal(localLocationCommand('near 02108 within 25 miles',filters)?.filters.radiusMiles,25);
assert.equal(localLocationCommand('find a blue R8 near 80487',filters),null);
assert.equal(coordinates(null,null),null);assert.equal(coordinates('',''),null);
assert.equal(locationMatches({},filters),false);
assert.equal(locationMatches({coordinates:{latitude:40.63,longitude:-106.93}},filters),true);
assert.equal(locationMatches({coordinates:{latitude:39.74,longitude:-104.99}},filters),false);
assert.equal(locationMatches({locationQuery:{zip:'80487',radiusMiles:50}},filters),true);
assert.equal(locationMatches({locationQuery:{zip:'80487',radiusMiles:100}},filters),false);
assert.equal(locationMatches({locationQuery:{zip:'02108',radiusMiles:25}},filters),false);
assert.equal(locationMatches({},initialFilters),true);
assert.equal(milesBetween(filters.location!,filters.location!),0);
assert.equal(marketcheckUrl(filters,false).searchParams.get('zip'),'80487');
assert.equal(marketcheckUrl(filters,false).searchParams.get('radius'),'50');
assert.equal(autoDevUrl(filters).searchParams.get('distance'),'50');
assert.equal(autoDevUrl(filters).searchParams.has('retailListing.state'),false);
assert.deepEqual(marketplaceInput(filters).zipCodes,['80487']);assert.equal(marketplaceInput(filters).distanceMiles,50);
await assert.rejects(()=>lookupZip('00000',async()=>new Response('',{status:404})),/not found/);
await assert.rejects(()=>lookupZip('80487',async()=>{throw Error('network')}),/unavailable/);
await assert.rejects(()=>lookupZip('80487',async()=>Response.json({...response,'post code':'02108'})),/verify/);
assert.equal((await resolveZip({...filters,zip:''},request)).location,null);
